    @classmethod
    def generate_all_scripts(cls) -> list[AnimatedShortScript]:
        results: list[AnimatedShortScript] = []
        for defn in cls.TOPIC_DEFINITIONS:
            scenes = [
                AnimationScene(
                    scene_index=idx + 1,
                    title=sc[0],
                    narration=sc[1],
                    duration_seconds=sc[2],
                    pose=sc[3],
                    expression=sc[4],
                    camera_motion=sc[5],
                    theme=sc[6],
                    key_action=sc[7],
                )
                for idx, sc in enumerate(defn["scenes"])
            ]
            total_dur = sum(s.duration_seconds for s in scenes)
            desc = (
                f"{defn['title']}\n\n"
                f"{defn['hook']}\n\n"
                "Animated with open-source Blender & Godot engines.\n"
                "Original script and procedural animation by BENXAUTOMATION."
            )
            script = AnimatedShortScript(
                script_id=defn["id"],
                topic_category=defn["cat"],
                title=defn["title"],
                hook=defn["hook"],
                target_duration=total_dur,
                scenes=scenes,
                description=desc,
                tags=defn["tags"],
            )
            results.append(script)
        return results

    @classmethod
    def get_script(cls, script_id: str) -> AnimatedShortScript:
        all_s = cls.generate_all_scripts()
        for s in all_s:
            if s.script_id == script_id:
                return s
        raise ValueError(f"Script {script_id} not found.")
